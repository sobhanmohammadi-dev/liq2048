using Table = std::array<Glyph, 128>;

template <size_t N>
Table build(const Src (&src)[N], int height, char fallback) {
    Table t{};
    for (const Src& s : src) {
        Glyph g;
        g.w = uint8_t(std::strlen(s.r[0]));
        for (int r = 0; r < height; ++r)
            for (int c = 0; c < g.w; ++c)
                if (s.r[r][c] == '#') g.rows[r] |= uint8_t(1u << c);
        t[size_t(s.c)] = g;
    }
    for (Glyph& g : t)
        if (g.w == 0) g = t[size_t(fallback)];
    return t;
}

const Table& table(FontFace f) {
    static const Table a = build(k5x7, 7, '?');
    static const Table b = build(k3x5, 5, '?');
    return f == FontFace::Text5x7 ? a : b;
}

